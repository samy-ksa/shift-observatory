import { google } from 'googleapis';
const o = new google.auth.OAuth2(process.env.GSC_CLIENT_ID, process.env.GSC_CLIENT_SECRET);
o.setCredentials({ refresh_token: process.env.GSC_REFRESH_TOKEN });
const sc = google.searchconsole({ version: 'v1', auth: o });
const SITE = 'sc-domain:ksashiftobservatory.online';
const d = (n) => { const x = new Date(); x.setDate(x.getDate() - n); return x.toISOString().slice(0, 10); };
const q = async (dimensions, extra = {}) => (await sc.searchanalytics.query({ siteUrl: SITE, requestBody: { startDate: d(31), endDate: d(3), dimensions, rowLimit: 500, ...extra } })).data.rows ?? [];
const lang = (u) => (u.match(/\.online\/(en|fr|ar)(\/|$)/) || [, 'autre'])[1];
const agg = (rows, keyFn) => { const m = {}; for (const r of rows) { const k = keyFn(r); m[k] ??= { clicks: 0, impr: 0 }; m[k].clicks += r.clicks; m[k].impr += r.impressions; } return Object.entries(m).sort((a, b) => b[1].impr - a[1].impr); };
const byCountry = await q(['country']);
console.log('PAYS (28j)'); byCountry.slice(0, 12).forEach(r => console.log(r.keys[0], r.clicks, r.impressions));
const cp = await q(['country', 'page']);
console.log('\nARABIE SAOUDITE par langue'); console.log(agg(cp.filter(r => r.keys[0] === 'sau'), r => lang(r.keys[1])));
console.log('\nFRANCE par langue'); console.log(agg(cp.filter(r => r.keys[0] === 'fra'), r => lang(r.keys[1])));
console.log('\nTOUS par langue'); console.log(agg(cp, r => lang(r.keys[1])));
const gulf = ['sau', 'are', 'qat', 'kwt', 'bhr', 'omn'];
console.log('\nGOLFE par langue'); console.log(agg(cp.filter(r => gulf.includes(r.keys[0])), r => lang(r.keys[1])));
const top = cp.filter(r => gulf.includes(r.keys[0])).sort((a, b) => b.impressions - a.impressions).slice(0, 15);
console.log('\nTOP pages Golfe'); top.forEach(r => console.log(r.keys[0], r.clicks, r.impressions, r.keys[1].replace('https://www.ksashiftobservatory.online', '')));
const qs = await q(['country', 'query']);
console.log('\nTOP requêtes Arabie saoudite'); qs.filter(r => r.keys[0] === 'sau').sort((a, b) => b.impressions - a.impressions).slice(0, 15).forEach(r => console.log(r.clicks, r.impressions, r.position.toFixed(1), r.keys[1]));
